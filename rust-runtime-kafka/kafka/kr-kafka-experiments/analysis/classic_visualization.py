#!/usr/bin/env python3
"""Export checked Java/native evidence into the repository's experiment explorer."""
import argparse
from collections import Counter, defaultdict
import hashlib
import html
import json
import gzip
from pathlib import Path
import re
import tempfile

from classic_comparison import comparison_limits, fingerprint, load_report, require, validate
from classic_artifacts import open_artifact

ROOT = Path(__file__).resolve().parents[3]
ASSETS = ROOT / "tools/trace-tool"
SCHEMA = "kr-producer-comparison/v1"
COUNTS = ("offered", "accepted", "refused", "acked", "failed")
SERIES = (*COUNTS, "outstanding", "produce_requests", "produce_records", "committed", "wire_bytes")
QUANTILES = ("p50", "p90", "p99", "max")
MAX_TIME = 300_000_000_000
SAMPLE_SOURCE = ASSETS / "fixtures/producer-comparison-source.json.gz"
SAMPLE = ASSETS / "producer-comparison-data.js"
COMMENT = "// Generated by classic_visualization; do not edit."


def compact(value):
    return json.dumps(value, separators=(",", ":"), ensure_ascii=False)


def digest(path):
    with path.open("rb") as file:
        return hashlib.file_digest(file, "sha256").hexdigest()


def quantiles(values):
    values.sort()
    return {name: values[(len(values) * rank + 99) // 100 - 1] if values else None
            for name, rank in zip(QUANTILES, (50, 90, 99, 100), strict=True)}


def peek_duration(report):
    if "environment" in report:
        return report["environment"]["now_ns"]
    # The bridge's streaming export deliberately writes now_ns first. Full
    # hashes and semantic time bounds are verified when this run is loaded.
    with open_artifact(report["artifacts"]["environment"]) as file:
        match = re.match(rb'^\{"now_ns":([0-9]+),', file.read(128))
    require(match is not None, "streamed environment duration prefix")
    return int(match[1])


def uuid(value):
    return bytes(value).hex()


def derive_run(report, width, count):
    checked = validate(report)
    duration = report["environment"]["now_ns"]
    require(0 < duration <= MAX_TIME, "viewer duration bound")
    require(report["offered"] <= 1_000_000, "viewer population bound")
    series = {key: [0] * count for key in SERIES}
    latency = [[] for _ in range(count)]
    accepted, offered, consumed = {}, {}, {}

    def bucket(at):
        require(0 <= at <= duration, "event outside realized duration")
        return min(count - 1, at // width)

    for event in report["external_history"]:
        kind, at = event["kind"], event["at_ns"]
        b = bucket(at)
        if kind == "offer":
            offered[event["id"]] = at
            series["offered"][b] += 1
        elif kind == "admission" and event["accepted"]:
            accepted[event["id"]] = at
            series["accepted"][b] += 1
        elif kind == "consumed":
            consumed[event["id"]] = at
    # A pending closed-loop candidate can become a refusal at source end with
    # no separate Refused event. The stable offered-minus-admitted population
    # accounts for it at its original offer time, exactly once.
    for record_id in offered.keys() - accepted.keys():
        series["refused"][bucket(offered[record_id])] += 1
    routes = {r["id"]: (uuid(r["topic_id"]), r["partition"])
              for r in report["environment"]["log"]}
    origin = report["manifest"]["start_ns"]
    writes, brokers, broker_series = {}, {}, {}
    for broker in report["manifest"]["brokers"]:
        broker_series[broker["id"]] = {"id": broker["id"], "committed": [0] * count,
                                        "produce_requests": [0] * count, "wire_bytes": [0] * count}
    for entry in report["environment"]["history"]["entries"]:
        kind, body = next(iter(entry["event"].items()))
        b = bucket(entry["now_ns"] - origin)
        if kind == "ConnectionOpened":
            brokers[body["connection"]] = body["broker"]
        elif kind == "Accepted":
            routes.setdefault(body["record_id"], (uuid(body["topic"]), body["partition"]))
        elif kind == "WriteAdmitted":
            writes[body["operation"]] = brokers[body["connection"]]
        elif kind == "WriteCompleted":
            broker = writes.pop(body["operation"])
            series["wire_bytes"][b] += body["bytes"]
            broker_series[broker]["wire_bytes"][b] += body["bytes"]
        elif kind == "BrokerRequest" and body["api"] == 0:
            series["produce_requests"][b] += 1
            series["produce_records"][b] += len(body["records"])
            broker_series[brokers[body["connection"]]]["produce_requests"][b] += 1
        elif kind == "BrokerCommit":
            series["committed"][b] += body["records"]
            broker_series[brokers[body["connection"]]]["committed"][b] += body["records"]
    partitions = {}
    reasons = Counter()
    for delivery in report["deliveries"]:
        record_id, at = delivery["id"], delivery["at_ns"]
        require(at == consumed[record_id], "consumed delivery clock")
        b, key = bucket(at), "acked" if delivery["success"] else "failed"
        series[key][b] += 1
        if delivery["success"]:
            latency[b].append(at - accepted[record_id])
        else:
            reason = delivery.get("error")
            if reason is None:
                reason = f"{ {1: 'NotWritten', 2: 'Unknown'}[delivery['outcome']]} / reason {delivery['reason']}"
            reasons[reason] += 1
        route = routes.get(record_id)
        # Unknown/unresolved routing remains distinct from partition zero.
        if route is None or route[1] < 0:
            route = ("", -1)
        row = partitions.setdefault(route, {"topic_id": route[0], "partition": route[1],
                                            "acked": [0] * count, "failed": [0] * count})
        row[key][b] += 1
    outstanding = 0
    for b in range(count):
        outstanding += series["accepted"][b] - series["acked"][b] - series["failed"][b]
        require(outstanding >= 0, "negative bucket outstanding")
        series["outstanding"][b] = outstanding
    require(outstanding == 0, "unsettled chart population")
    all_latencies = [value for group in latency for value in group]
    summary = {key: report[key] for key in COUNTS}
    summary.update(quantiles(all_latencies))
    require(summary["p99"] == checked["ack_latency_p99_ns"], "independent p99 differs")
    distribution = Counter(all_latencies)
    cumulative, ecdf = 0, []
    for value, population in sorted(distribution.items()):
        cumulative += population
        ecdf.append({"latency": value, "count": cumulative})
    complete = len(ecdf) <= 512
    if not complete:
        ecdf = [ecdf[i * (len(ecdf) - 1) // 511] for i in range(512)]
    q = [quantiles(group) for group in latency]
    series.update({key: [row[key] for row in q] for key in QUANTILES})
    require(len(partitions) <= 1024, "partition chart bound")
    return {"duration_ns": duration, "summary": summary, "buckets": series,
            "partitions": [partitions[key] for key in sorted(partitions)],
            "brokers": list(broker_series.values()), "ecdf": ecdf, "ecdf_complete": complete,
            "failure_reasons": [{"label": label, "count": n} for label, n in sorted(reasons.items())],
            "sender_errors": checked["sender_errors"], "max_source_lag_ns": checked["max_source_lag_ns"],
            "fault_phases": checked["phases"], "coverage_gaps": checked["coverage_gaps"]}


def describe_setup(manifest, original, classic_config, adjustments):
    loads = []
    for load in manifest["experiment"]["loads"]:
        kind, shape = next(iter(load["shape"].items()))
        t = load["template"]
        if kind == "OpenLoop":
            shape_text = f"{shape['rate_per_s']:,} offers/s until {shape['end_ns'] / 1e9:g} s"
        else:
            shape_text = f"{shape['outstanding']:,} outstanding; up to {shape.get('count', shape.get('max_offers')):,} offers"
            if "end_ns" in shape:
                shape_text += f" until {shape['end_ns'] / 1e9:g} s"
        loads.append(f"At {shape['start_ns'] / 1e9:g} s: {kind}, {shape_text}; topic {manifest['topics'][t['topic']]['name']}, "
                     f"{t['value_bytes']:,}-byte {t['value_pattern']} values; routing {compact(t['partitioning'])}.")
    p, d = manifest["producer"], manifest["driver"]
    mode = p.get("batch_target_mode", "Raw")
    settings = [f"Native batch target mode: {mode} (including the batch header in EstimatedWire mode).",
                f"Requests per connection: {p['max_in_flight_per_connection']}; batch target: {p['batch_target_bytes']:,} bytes; "
                f"linger: {p['linger_max'] / 1e6:g} ms; request timeout: {p['request_timeout'] / 1e6:g} ms; "
                f"delivery timeout: {p['delivery_timeout'] / 1e6:g} ms; compression: {compact(p['compression'])}.",
                f"{len(manifest['brokers'])} brokers; {sum(len(t['leaders']) for t in manifest['topics']):,} initial partitions. "
                f"Pipe: {d['pipe_bytes']:,} bytes; chunks: {d['chunk_bytes']:,} bytes; service delay: {d['service_delay_ns'] / 1e6:g} ms; "
                f"I/O jitter: {d['jitter_ns'] / 1e6:g} ms."]
    settings.extend(f"Broker {link['broker']}: propagation {link['to_broker_latency_ns'] / 1e6:g} ms outbound / "
                    f"{link['from_broker_latency_ns'] / 1e6:g} ms return." for link in manifest['faults'].get('links', []))
    # The provenance pane preserves the actual knobs as inert strings; it never
    # asks JavaScript to round full-width native values.
    config = [{"name": key, "native": compact(value)} for key, value in sorted(p.items())]
    java = [{"name": key, "java": compact(value)} for key, value in sorted(classic_config.items())]
    return {"loads": loads, "settings": settings, "adjustments": adjustments,
            "original_manifest_sha256": fingerprint(original), "native_config": config, "java_config": java}


def environment(manifest):
    faults = manifest["faults"]
    bands = []
    for kind, windows in [("isolation", faults.get("isolations", [])),
                          ("link", faults.get("link_outages", [])),
                          ("rule", faults.get("environment", [])),
                          ("polling pause", manifest["experiment"]["polling_pauses"])]:
        for index, window in enumerate(windows):
            detail = {k: v for k, v in window.items() if k not in {"start_ns", "end_ns"}}
            bands.append({"kind": kind, "start": window["start_ns"], "end": window["end_ns"],
                          "label": f"{kind} {index}: {compact(detail)}"})
    markers = [{"at": action["at_ns"], "label": compact(action["action"])}
               for action in manifest["experiment"]["scheduled_actions"]]
    return {"bands": bands, "markers": markers}


def build_pair(paths, on_report=None):
    headers = {adapter: json.loads(path.read_text()) for adapter, path in paths.items()}
    classic, native = headers["classic"], headers["native"]
    require(classic["manifest"] == native["manifest"], "different effective inputs")
    scenario, variant, _, profile, size, seed = paths["classic"].stem.split("--")
    duration = max(peek_duration(header) for header in headers.values())
    require(0 < duration <= MAX_TIME, "pair duration bound")
    width = max(1, (duration + 319) // 320)
    count = (duration + width - 1) // width
    result = {"variant": variant, "profile": profile, "size": size, "seed": seed,
              "origin_ns": str(classic["manifest"]["start_ns"]), "duration_ns": duration,
              "bucket_ns": width, "bucket_count": count, "replay_verified": True,
              "manifest_sha256": fingerprint(classic["manifest"]), "environment": environment(classic["manifest"]),
              "limits": comparison_limits(scenario, classic),
              "setup": describe_setup(classic["manifest"], classic["original_manifest"], classic["classic_config"], classic["adjustments"]),
              "sources": [{"adapter": adapter, "file": path.name, "sha256": digest(path)} for adapter, path in paths.items()],
              "runs": {}}
    for adapter, path in paths.items():
        report = load_report(path)
        result["runs"][adapter] = derive_run(report, width, count)
        if on_report is not None:
            on_report(adapter, report)
        del report
    result["fault_exposure_comparable"] = not any(run["coverage_gaps"] for run in result["runs"].values())
    return scenario, result


def reviewed_assets():
    pins = json.loads((ROOT / "kafka/kr-kafka-experiments/src/export/asset-hashes.json").read_text())
    assets = {}
    for name, expected in pins.items():
        path = ASSETS / name
        require(digest(path) == expected, f"reviewed viewer asset changed: {name}")
        assets[name] = path.read_text()
    return assets


def generate_sample():
    """Regenerate one checked recovery pair from its complete compressed evidence."""
    with gzip.open(SAMPLE_SOURCE, "rt") as file:
        sources = json.load(file)
    with tempfile.TemporaryDirectory(prefix="classic-viewer-sample-") as directory:
        paths = {}
        for adapter, source in sources.items():
            path = Path(directory) / source["file"]
            require(path.parent == Path(directory), "sample path")
            path.write_text(source["text"])
            paths[adapter] = path
        scenario, pair = build_pair(paths)
    return f'{COMMENT}\nglobalThis.PRODUCER_EXPERIMENT_DATA = {compact({"schema": SCHEMA, "scenario": scenario, "pairs": [pair]})};\n'


def page_html(assets, bundle):
    data = compact(bundle).replace("<", "\\u003c").replace("\u2028", "\\u2028").replace("\u2029", "\\u2029")
    require(len(data.encode()) <= 48 * 1024 * 1024, "comparison artifact byte bound")
    page = assets["producer-experiment.html"]
    for name, source in assets.items():
        if name.endswith(".css"):
            page = page.replace(f'<link rel="stylesheet" href="./{name}">', f"<style>\n{source}\n</style>")
        elif name.endswith(".js"):
            require("</script" not in source.lower(), "script source terminator")
            page = page.replace(f'<script src="./{name}"></script>', f"<script>\n{source}\n</script>")
    page = page.replace('<script src="./producer-experiment-data.js"></script>',
                        '<script>\n// Generated by classic_visualization; do not edit.\n'
                        f'globalThis.PRODUCER_EXPERIMENT_DATA = {data};\n</script>')
    page = page.replace('<main id="experiment">', '<main id="experiment"><nav><a href="index.html">All Java/native comparisons</a></nav>')
    require('<script src=' not in page and '<link rel="stylesheet"' not in page, "standalone viewer asset inventory")
    return page


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("directories", type=Path, nargs="*")
    parser.add_argument("--out", type=Path)
    parser.add_argument("--sample", action="store_true", help="regenerate the byte-pinned recovery sample")
    parser.add_argument("--scenario", default=".*")
    args = parser.parse_args()
    if args.sample:
        SAMPLE.write_text(generate_sample())
        return
    require(args.out is not None and args.directories, "input directories and --out are required")
    paths = defaultdict(dict)
    for directory in args.directories:
        for path in sorted(directory.glob("*--*.json")):
            if len(path.stem.split("--")) != 6 or any(token in path.name for token in [".first.", ".second.", ".failure."]):
                continue
            scenario, variant, adapter, profile, size, seed = path.stem.split("--")
            require(re.fullmatch(r"[a-z0-9.-]{1,128}", scenario) is not None, "scenario filename")
            require(profile in {"original", "common"} and size in {"test", "full"}, "profile/size")
            require(re.fullmatch(r"0|[1-9][0-9]*", seed) is not None and int(seed) < 2**64, "seed")
            if not re.fullmatch(args.scenario, scenario):
                continue
            require(adapter in {"classic", "native"}, "adapter name")
            key = (scenario, variant, profile, size, seed)
            require(adapter not in paths[key], "duplicate input run")
            paths[key][adapter] = path
    require(0 < len(paths) <= 4096, "gallery requires 1..4096 comparison pairs")
    assets = reviewed_assets()
    groups = defaultdict(list)
    for key, pair in sorted(paths.items()):
        require(set(pair) == {"classic", "native"}, f"missing counterpart: {key}")
        scenario, result = build_pair(pair)
        groups[(scenario, key[3])].append(result)
        print("Checked", "/".join(key), flush=True)
    export_groups(groups, args.out, assets)


def export_groups(groups, out, assets=None):
    """Export already checked pairs, also used by the incremental Full review."""
    assets = reviewed_assets() if assets is None else assets
    out.mkdir(parents=True, exist_ok=True)
    rows = []
    for (scenario, size), pairs in groups.items():
        # Common first, then exact original inputs. Each option is one matched pair.
        pairs.sort(key=lambda p: (p["profile"] != "common", p["variant"], int(p["seed"])))
        for index in range(0, len(pairs), 16):
            chunk = pairs[index:index + 16]
            bundle = {"schema": SCHEMA, "scenario": scenario, "pairs": chunk}
            name = f"{scenario}--{size}--{index // 16 + 1}"
            (out / f"{name}.json").write_text(compact(bundle) + "\n")
            (out / f"{name}.html").write_text(page_html(assets, bundle))
            for i, pair in enumerate(chunk):
                c, n = pair["runs"]["classic"]["summary"], pair["runs"]["native"]["summary"]
                p99 = lambda r: "—" if r["p99"] is None else f"{r['p99'] / 1e6:,.3f}"
                rows.append((size, f'<tr><td><a href="{name}.html#pair={i}">{html.escape(scenario)}</a></td>'
                            f'<td>{html.escape(pair["variant"])}</td><td>{size}</td><td>{pair["profile"]}</td>'
                            f'<td>{c["acked"]:,} / {n["acked"]:,}</td><td>{c["refused"]:,} / {n["refused"]:,}</td>'
                            f'<td>{p99(c)} / {p99(n)}</td><td>{"exposure gap" if not pair["fault_exposure_comparable"] else "checked"}'
                            f'{"; semantic limits" if pair["limits"] else ""}</td></tr>'))
    gallery = '<!doctype html><html lang="en"><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1">'
    gallery += '<title>Java vs native producer comparisons</title><style>' + assets['trace-viewer.css'] + assets['producer-experiment.css'] + '</style>'
    gallery += '<main><p class="eyebrow">Deterministic producer experiments</p><h1>Java vs native producer</h1>'
    gallery += '<p>Choose a matched pair to overlay delivery, admission, latency, outstanding work and broker traffic on a shared simulation clock.</p>'
    gallery += '<p>All values below are <strong>classic Java / native</strong>. Common adjusts unsupported controls; original preserves the original manifest. '
    gallery += 'Closed-loop counts can differ because deliveries feed the source. P99 includes acknowledged records only.</p>'
    gallery += f'<p>{sum(len(pairs) for pairs in groups.values())} matched pairs, each replay verified. Fault-exposure gaps and semantic limits remain visible on every detail page.</p>'
    for size, title in [('full', 'Full-size comparisons'), ('test', 'Test-size comparisons')]:
        selected_rows = [row for row_size, row in rows if row_size == size]
        if not selected_rows:
            continue
        gallery += f'<h2>{title}</h2><div class="table-scroll"><table><thead><tr>'
        gallery += ''.join(f'<th>{h}</th>' for h in ['Scenario', 'Variant', 'Size', 'Profile', 'Acknowledged', 'Refused', 'P99 (ms)', 'Comparison'])
        gallery += '</tr></thead><tbody>' + ''.join(selected_rows) + '</tbody></table></div>'
    gallery += '</main></html>'
    require(len(gallery.encode()) <= 16 * 1024 * 1024, "gallery byte bound")
    (out / "index.html").write_text(gallery)
    print(out / "index.html", flush=True)


if __name__ == "__main__":
    main()
