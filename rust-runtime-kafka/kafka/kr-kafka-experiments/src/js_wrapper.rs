//! Standalone JavaScript is not HTML. Keep the two encoding boundaries explicit.
use serde::{Deserialize, Serialize};
pub const COMMENT: &str = "// Generated by generate_producer_experiment; do not edit.";
pub const ASSIGNMENT: &str = "globalThis.PRODUCER_EXPERIMENT_DATA = ";
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct DecimalU64(pub u64);
impl Serialize for DecimalU64 {
    fn serialize<S: serde::Serializer>(&self, s: S) -> Result<S::Ok, S::Error> {
        s.serialize_str(&self.0.to_string())
    }
}
impl<'de> Deserialize<'de> for DecimalU64 {
    fn deserialize<D: serde::Deserializer<'de>>(d: D) -> Result<Self, D::Error> {
        let s = String::deserialize(d)?;
        let v = s.parse::<u64>().map_err(serde::de::Error::custom)?;
        if s != v.to_string() {
            return Err(serde::de::Error::custom("noncanonical u64"));
        }
        Ok(Self(v))
    }
}
pub fn standalone(value: &impl Serialize) -> Result<String, String> {
    Ok(format!(
        "{COMMENT}\n{ASSIGNMENT}{};\n",
        serde_json::to_string(value).map_err(|e| e.to_string())?
    ))
}
pub fn html_json(value: &impl Serialize) -> Result<String, String> {
    Ok(serde_json::to_string(value)
        .map_err(|e| e.to_string())?
        .replace('&', "\\u0026")
        .replace('<', "\\u003c")
        .replace('>', "\\u003e")
        .replace('\u{2028}', "\\u2028")
        .replace('\u{2029}', "\\u2029"))
}
